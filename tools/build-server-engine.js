// Packages public/engine.js and public/daily-core.js as an ES module for the Cloudflare
// Functions, so the server scores daily challenges with exactly the same ranges as the site.
// Rerun after changing either file:  node tools/build-server-engine.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = ['public/engine.js', 'public/daily-core.js'].map(f => fs.readFileSync(path.join(root, f), 'utf8'));
const out = `// GENERATED by tools/build-server-engine.js from public/engine.js and public/daily-core.js. Do not edit.
${src.join('\n')}
export { DAILY, HANDS };
`;
fs.writeFileSync(path.join(root, 'lib', 'engine.mjs'), out);
console.log('Wrote lib/engine.mjs');
